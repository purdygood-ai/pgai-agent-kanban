#!/usr/bin/env python3
"""
regenerate_changelog.py — rebuild CHANGELOG.md from a release-notes directory.

The renderer behind scripts/regenerate-changelog.sh, which resolves the
project's release-notes/ directory and output path and calls this module.

What it writes:
  - every *.md file in RELEASE_NOTES_DIR whose name starts with
    v<major>.<minor>.<patch>, newest version first (selected and ordered by
    pgai_agent_kanban.lib.semver, the shared version helper);
  - each as a "## <version> — <date>" section holding the file's text with
    its first H1 title line removed, sections separated by "---" rules,
    under a fixed "# Changelog" header;
  - "*(no releases found)*" in place of the sections when no file matches,
    after a WARNING line on stdout.

The date follows the one rule in pgai_agent_kanban.cm.release_notes_date,
shared with the release-time changelog writer: **Release Date:**, else
**Date:**, else "unknown" with one stderr warning naming the file.

Usage (CLI):
    python3 -m pgai_agent_kanban.cm.regenerate_changelog RELEASE_NOTES_DIR OUTPUT_PATH

Prints the output path and the number of releases included, and exits 0.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

if not __package__:
    _OWN_PACKAGE_ROOT = str(pathlib.Path(__file__).resolve().parents[2])
    if _OWN_PACKAGE_ROOT not in sys.path:
        sys.path.insert(0, _OWN_PACKAGE_ROOT)

from pgai_agent_kanban.cm.release_notes_date import read_release_date  # noqa: E402
from pgai_agent_kanban.lib.semver import from_filename, version_sort_key  # noqa: E402

HEADER = (
    "# Changelog\n\n"
    "<!-- Auto-generated by scripts/cm/release.sh. Do not edit manually. -->\n"
)

_UNKNOWN_DATE = "unknown"


def leading_version(path: pathlib.Path) -> str:
    """Return the vX.Y.Z token *path*'s stem begins with, or "" when it begins with none.

    "v1.2.3.md" and "v1.2.3-draft.md" carry "v1.2.3"; "notes-v1.2.3.md" carries
    none, because its version token is not at the start of the name.
    """
    token = from_filename(path.stem)
    return token if token and path.stem.startswith(token) else ""


def strip_h1_title(text: str) -> str:
    """Remove the first top-level H1 line from *text*, and the blank lines it leaves."""
    result = []
    skipped = False
    for line in text.splitlines():
        if not skipped and re.match(r"^#[^#]", line):
            skipped = True
            continue
        result.append(line)
    return "\n".join(result).lstrip("\n")


def render_changelog(release_notes_dir: pathlib.Path) -> tuple[str, int]:
    """Return the CHANGELOG.md text for *release_notes_dir* and its release count.

    Warns on stdout when no versioned notes file is found, and on stderr once
    for each notes file that carries no date line.
    """
    candidates = [p for p in release_notes_dir.glob("*.md") if leading_version(p)]
    if not candidates:
        print(
            f"WARNING: no versioned release notes files found in {release_notes_dir}",
            flush=True,
        )
    candidates.sort(key=lambda p: version_sort_key(leading_version(p)), reverse=True)

    sections = []
    for path in candidates:
        text = path.read_text(encoding="utf-8")
        release_date = read_release_date(text, path) or _UNKNOWN_DATE
        sections.append(f"## {path.stem} — {release_date}\n\n{strip_h1_title(text)}")

    if sections:
        combined = "\n\n---\n\n".join(sections)
        content = f"{HEADER}\n---\n\n{combined}\n\n---\n"
    else:
        content = f"{HEADER}\n---\n\n*(no releases found)*\n\n---\n"
    return content, len(candidates)


def main(argv: list[str] | None = None) -> int:
    """Parse RELEASE_NOTES_DIR and OUTPUT_PATH, write the rendered CHANGELOG
    to OUTPUT_PATH, print where it went and how many releases it holds, and
    return 0."""
    parser = argparse.ArgumentParser(
        prog="python3 -m pgai_agent_kanban.cm.regenerate_changelog",
        description="Rebuild CHANGELOG.md from a release-notes directory.",
    )
    parser.add_argument("release_notes_dir", type=pathlib.Path,
                        help="directory holding the vX.Y.Z*.md release-notes files")
    parser.add_argument("output_path", type=pathlib.Path,
                        help="path the CHANGELOG is written to")
    args = parser.parse_args(argv)

    content, count = render_changelog(args.release_notes_dir)
    args.output_path.write_text(content, encoding="utf-8")
    print(f"CHANGELOG.md written to: {args.output_path}", flush=True)
    print(f"Releases included: {count}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
